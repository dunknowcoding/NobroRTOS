#!/usr/bin/env python3
"""Generate the typed Rust exact-board catalog from canonical board.json files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys


REPO = Path(__file__).resolve().parents[2]
BOARD_ROOT = REPO / "core" / "boards"
OUTPUT = REPO / "core" / "crates" / "nobro_hal" / "src" / "generated_board_profiles.rs"


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def rust_option_string(value: object) -> str:
    return "None" if value is None else f"Some({rust_string(str(value))})"


def rust_option_u32(value: object) -> str:
    if value is None:
        return "None"
    parsed = int(value, 0) if isinstance(value, str) else int(value)
    return f"Some({parsed})"


def rust_pin(value: object) -> str:
    if value is None:
        return "None"
    parsed = int(value)
    if not 0 <= parsed <= 255:
        raise ValueError(f"pin {parsed} is outside u8")
    return f"Some({parsed})"


def rust_const_name(board_id: str) -> str:
    return "EXACT_" + re.sub(r"[^A-Za-z0-9]+", "_", board_id).strip("_").upper()


def load_profiles() -> list[dict]:
    profiles = []
    for path in sorted(BOARD_ROOT.glob("*/*/board.json")):
        with path.open(encoding="utf-8") as handle:
            data = json.load(handle)
        data["_path"] = path.relative_to(REPO).as_posix()
        profiles.append(data)
    return profiles


def render(profiles: list[dict]) -> str:
    lines = [
        "// @generated by tools/build/generate_board_catalog.py; do not edit.",
        "",
        f"pub const EXACT_BOARD_PROFILES: [ExactBoardProfileDefinition; {len(profiles)}] = [",
    ]
    for profile in profiles:
        composition = profile["composition"]
        boot = profile["boot"]
        capacity = profile["capacity"]
        pins = profile["pins"]
        aliases = ", ".join(rust_string(alias) for alias in profile["feature_aliases"])
        lines.extend(
            [
                "    ExactBoardProfileDefinition {",
                f"        source: {rust_string(profile['_path'])},",
                f"        schema: {rust_string(profile['schema'])},",
                f"        board_id: {rust_string(profile['board_id'])},",
                f"        platform_id: {rust_string(profile['platform_id'])},",
                f"        feature: {rust_string(profile['feature'])},",
                f"        feature_aliases: &[{aliases}],",
                f"        silicon_id: {rust_option_string(composition['silicon'])},",
                f"        physical_board_id: {rust_string(composition['physical_board'])},",
                f"        boot_layout_id: {rust_string(composition['boot_layout'])},",
                f"        framework_core_id: {rust_option_string(composition['framework_core'])},",
                f"        hal_stack_id: {rust_option_string(composition['hal_stack'])},",
                f"        usb_stack_id: {rust_option_string(composition['usb_stack'])},",
                f"        boot_layout: {rust_string(boot['layout'])},",
                f"        app_flash_start: {rust_option_u32(boot['app_flash_start'])},",
                f"        app_flash_len_bytes: {rust_option_u32(boot['app_flash_len_bytes'])},",
                f"        ram_start: {rust_option_u32(boot['ram_start'])},",
                f"        ram_len_bytes: {rust_option_u32(boot['ram_len_bytes'])},",
                "        capacity: BoardCapacity::new("
                f"{int(capacity['flash_budget_bytes'])}, "
                f"{int(capacity['ram_budget_bytes'])}, "
                f"{int(capacity['sample_pool_slots'])}, "
                f"{int(capacity['max_modules'])}),",
                "        pins: BoardPins::optional("
                f"{rust_pin(pins['led'])}, "
                f"{rust_pin(pins['servo_pwm'])}, "
                f"{rust_pin(pins['mvk_trigger'])}),",
                f"        firmware_support: {rust_string(profile['firmware_generation']['support'])},",
                "    },",
            ]
        )
    lines.extend(["];", ""])
    for index, profile in enumerate(profiles):
        lines.append(
            f"pub const {rust_const_name(profile['board_id'])}: "
            f"ExactBoardProfileDefinition = EXACT_BOARD_PROFILES[{index}];"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the checked-in Rust catalog differs from canonical JSON",
    )
    args = parser.parse_args()
    try:
        rendered = render(load_profiles())
    except (KeyError, TypeError, ValueError, json.JSONDecodeError) as error:
        print(f"board catalog generation failed: {error}", file=sys.stderr)
        return 1
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(
                "generated board catalog is stale; run "
                "python tools/build/generate_board_catalog.py",
                file=sys.stderr,
            )
            return 1
        print(f"generated board catalog matches {len(load_profiles())} canonical profiles")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)} from {len(load_profiles())} profiles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
